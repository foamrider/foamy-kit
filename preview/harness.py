"""Isolated offscreen Quickshell runs against a chosen Omarchy shell host.

Shared by preview/render.py and tests/. Each run gets a fresh temporary root:

  <root>/shell.qml     generated by the caller
  <root>/Commons       -> <host>/Commons            (symlink, read-only)
  <root>/Ui/           symlinks to <host>/Ui/*, except KeyboardPanel.qml,
                       which is the host file with its PanelWindow swapped
                       for FakePanelWindow (offscreen Qt has no layer shell)
  <root>/plugin        -> the plugin directory
  <root>/harness/      preview/qml/*.qml (mock bar, screen)
  <root>/home, xdg dirs, runtime dir; theme colors.toml in the temp HOME

The environment drops WAYLAND_DISPLAY, HYPRLAND_INSTANCE_SIGNATURE and
DISPLAY, points HOME and every XDG_* directory into the root, and uses the
offscreen platform with a 1920x1080 screen and the software renderer, so
nothing reaches the live session. OMARCHY_PATH points at a stub holding only
the host's i18n catalogs (data); no host script or binary is ever run.
"""
import json
import os
import re
import shutil
import signal
import subprocess
import tempfile
from pathlib import Path

KIT_ROOT = Path(__file__).resolve().parents[1]
PREVIEW = KIT_ROOT / "preview"
HOSTS = {
    "4.0": Path(os.environ.get("FOAMY_HOST_40", "/usr/share/omarchy/shell")),
    "4.5": Path(os.environ.get("FOAMY_HOST_45", "/tmp/omarchy-ref/v45/shell")),
}
SCREEN = (1920, 1080)
FAILURE_MARKERS = ("ReferenceError", "TypeError", "Failed to load configuration",
                   "Cannot assign", "Unable to assign", "Non-existent attached object", "SAVE FAILED")


def host_dir(name):
    if name not in HOSTS:
        raise SystemExit(f"unknown host {name!r}; use one of {', '.join(HOSTS)}")
    path = HOSTS[name]
    if not (path / "Commons").is_dir() or not (path / "Ui").is_dir():
        raise SystemExit(f"host {name} not found at {path} (set FOAMY_HOST_{name.replace('.', '')})")
    return path


def transform_keyboard_panel(text):
    """The host KeyboardPanel with PanelWindow -> FakePanelWindow.

    Layer-shell attached properties are dropped (the namespace is kept as
    `layerNamespace` so tests can check it); `anchors { … }` window blocks
    become `windowAnchors { … }`. Geometry, motion and content are untouched."""
    out, skipping = [], False
    for line in text.splitlines():
        stripped = line.strip()
        if skipping:
            if stripped.startswith("?") or stripped.startswith(":"):
                continue
            skipping = False
        match = re.match(r"(\s*)WlrLayershell\.namespace\s*:(.*)$", line)
        if match:
            out.append(f"{match.group(1)}layerNamespace:{match.group(2)}")
            continue
        if re.match(r"WlrLayershell\.\w+\s*:", stripped):
            skipping = True
            continue
        line = re.sub(r"\bPanelWindow\s*\{", "FakePanelWindow {", line)
        line = re.sub(r"^(\s*)anchors\s*\{\s*$", r"\1windowAnchors {", line)
        out.append(line)
    result = "\n".join(out) + "\n"
    if "FakePanelWindow {" not in result:
        raise SystemExit("host KeyboardPanel.qml changed shape: no PanelWindow root to replace")
    return result


def build_ui(host, dest):
    dest.mkdir()
    for path in sorted((host / "Ui").iterdir()):
        if path.name in ("KeyboardPanel.qml", "qmldir"):
            continue
        (dest / path.name).symlink_to(path)
    (dest / "KeyboardPanel.qml").write_text(transform_keyboard_panel((host / "Ui/KeyboardPanel.qml").read_text()))
    for name in ("FakePanelWindow.qml", "FakeAnchors.qml", "FakeDisplay.qml"):
        shutil.copyfile(PREVIEW / "fakeui" / name, dest / name)
    qmldir = (host / "Ui/qmldir").read_text().rstrip("\n")
    qmldir += "\nFakePanelWindow 1.0 FakePanelWindow.qml\nFakeAnchors 1.0 FakeAnchors.qml\nsingleton FakeDisplay 1.0 FakeDisplay.qml\n"
    (dest / "qmldir").write_text(qmldir)


class Run:
    def __init__(self, host, shell_qml, plugin=None, theme="dark", language=None, extra=None, prefix="foamy-kit-run-"):
        self.host_name = host
        self.host = host_dir(host)
        self.base = Path(tempfile.mkdtemp(prefix=prefix))
        self.root = self.base / "shell"
        self.root.mkdir()
        (self.root / "Commons").symlink_to(self.host / "Commons", target_is_directory=True)
        build_ui(self.host, self.root / "Ui")
        if plugin:
            (self.root / "plugin").symlink_to(Path(plugin).resolve(), target_is_directory=True)
        harness = self.root / "harness"
        harness.mkdir()
        for path in (PREVIEW / "qml").glob("*.qml"):
            shutil.copyfile(path, harness / path.name)
        (self.root / "shell.qml").write_text(shell_qml)
        for name, text in (extra or {}).items():
            target = self.root / name
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(text)
        self.out = self.base / "out"
        self.out.mkdir()
        self.env = self._environment(theme, language)

    def _environment(self, theme, language):
        home = self.base / "home"
        state = home / ".local/state"
        theme_dir = state / "omarchy/current/theme"
        theme_dir.mkdir(parents=True)
        if theme:
            source = Path(theme) if os.path.sep in str(theme) else PREVIEW / "themes" / f"{theme}.toml"
            shutil.copyfile(source, theme_dir / "colors.toml")
        runtime = self.base / "runtime"
        runtime.mkdir(mode=0o700)
        omarchy = self.base / "omarchy"
        (omarchy / "default").mkdir(parents=True)
        catalogs = self.host.parent / "default/i18n"
        if catalogs.is_dir():
            (omarchy / "default/i18n").symlink_to(catalogs, target_is_directory=True)
        language_file = self.base / "language"
        language_file.write_text((language or "en") + "\n")
        screens = self.base / "screens.json"
        screens.write_text(json.dumps({"screens": [{"name": "FOAMY-1", "x": 0, "y": 0, "width": SCREEN[0], "height": SCREEN[1],
                                                    "logicalDpi": 96, "logicalBaseDpi": 96, "dpr": 1}]}))
        env = {key: value for key, value in os.environ.items()
               if key not in ("WAYLAND_DISPLAY", "HYPRLAND_INSTANCE_SIGNATURE", "DISPLAY", "QT_QPA_PLATFORM",
                              "QT_QPA_PLATFORMTHEME", "QT_STYLE_OVERRIDE", "QML_IMPORT_PATH", "QML2_IMPORT_PATH",
                              "LC_ALL", "LANGUAGE", "OMARCHY_PATH", "XDG_CURRENT_DESKTOP")
               and (not key.startswith("XDG_") or key in ("XDG_DATA_DIRS", "XDG_CONFIG_DIRS"))}
        env.update({
            "HOME": str(home),
            "XDG_CONFIG_HOME": str(home / ".config"),
            "XDG_STATE_HOME": str(state),
            "XDG_CACHE_HOME": str(home / ".cache"),
            "XDG_DATA_HOME": str(home / ".local/share"),
            "XDG_RUNTIME_DIR": str(runtime),
            "QT_QPA_PLATFORM": f"offscreen:configfile={screens}",
            "QT_QUICK_BACKEND": "software",
            "QT_QPA_PLATFORMTHEME": "basic",
            "LANG": "en_US.UTF-8",
            "OMARCHY_PATH": str(omarchy),
            "OMARCHY_LANGUAGE_FILE": str(language_file),
            "FOAMY_OUT": str(self.out),
            "FOAMY_HOST": self.host_name,
        })
        return env

    def run(self, timeout=40, done="FOAMY DONE"):
        log_path = self.base / "qs.log"
        with log_path.open("w") as log:
            process = subprocess.Popen(["qs", "-p", str(self.root), "--no-color"], env=self.env, stdout=log, stderr=log,
                                       start_new_session=True)
            try:
                process.wait(timeout=timeout)
            except subprocess.TimeoutExpired:
                pass
            finally:
                if process.poll() is None:
                    os.killpg(process.pid, signal.SIGTERM)
                    try:
                        process.wait(timeout=5)
                    except subprocess.TimeoutExpired:
                        os.killpg(process.pid, signal.SIGKILL)
        self.log = log_path.read_text(errors="replace")
        self.ok = done in self.log and not any(marker in self.log for marker in FAILURE_MARKERS) and "FOAMY FAIL" not in self.log
        return self

    def failures(self):
        return [line for line in self.log.splitlines()
                if "FOAMY FAIL" in line or any(marker in line for marker in FAILURE_MARKERS)]

    def cleanup(self):
        shutil.rmtree(self.base, ignore_errors=True)
